/// The set-1 scan code of a physical key, or null for keys a PC keyboard
/// does not have (media keys, the phone's own buttons).
int? scanOf(PhysicalKeyboardKey key) {
  final usage = key.usbHidUsage;
  if (usage >> 16 != 0x07) return null;
  return _hidToScan[usage & 0xFFFF];
}

class HardwareKeys {
  final _down = <int>{};

  /// Sends a key event to the host; false when it is not a PC key (Back,
  /// volume), which the phone keeps.
  bool handle(KeyEvent e, ScanOut send) {
    final code = scanOf(e.physicalKey);
    if (code == null) return false;
    final caps = HardwareKeyboard.instance.lockModesEnabled.contains(KeyboardLockMode.capsLock);
    switch (e) {
      case KeyDownEvent() || KeyRepeatEvent():
        _down.add(code);
        send(code, true, caps: caps);
      case KeyUpEvent():
        _down.remove(code);
        send(code, false, caps: caps);
    }
    return true;
  }

  /// Lets go of every key still down (the view closes).
  void releaseAll(ScanOut send) {
    for (final c in _down) {
      send(c, false);
    }
    _down.clear();
  }
}
